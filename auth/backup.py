"""Backup and restore of the accounts database (``db/auth.db``).

The file/name/validation machinery is a small engine (``Spec`` + helper
functions) that ``auth/log_backup.py`` reuses for the audit-log database; the
module-level functions below (``create``, ``list_backups``, ``restore`` ...)
are the accounts-database flavour of it.

Design notes
------------
* Backups are ordinary SQLite files in ``db/backups/`` (next to the database
  they protect, so the Docker volume ``../db:/app/db`` keeps them too).
* They are created with SQLite's online backup API, so the copy is
  consistent even while the application is running.
* File names are generated by this module and follow a strict pattern
  (``auth-YYYYMMDD-HHMMSS[-kind].db``). Every function that receives a name
  from the outside validates it against that pattern first, so a forged
  name such as ``../../etc/passwd`` can never reach the file system.
* A restore always makes a safety backup of the CURRENT database first
  (``-prerestore``), then copies the chosen backup over the live database
  with the same backup API (no file is replaced under an open connection).
* A backup file is only accepted (restore / import) when it is a healthy
  SQLite database that contains a ``users`` table with the columns the login
  needs and at least one active Superadmin -- so a restore can never lock
  everybody out.
* This module has NO permission checks. Application code must go through the
  ``@superadmin`` functions in ``auth.core`` (``create_backup`` ...), which
  also write the audit-log entries.
* The audit log lives in a separate file (``db/audit.db``) and is neither
  included in nor changed by a restore.
"""
from __future__ import annotations

import os
import re
import sqlite3
from contextlib import closing
from dataclasses import dataclass, field
from datetime import datetime, timedelta, timezone
from pathlib import Path
from typing import Callable

from i18n import t

BACKUP_DIRNAME = "backups"
KINDS = ("manual", "prerestore", "uploaded")
MAX_IMPORT_BYTES = 50 * 1024 * 1024  # 50 MB

_SQLITE_MAGIC = b"SQLite format 3\x00"
_REQUIRED_COLUMNS = {"id", "username", "password_hash", "role", "is_active", "expire_date"}
_VALID_ROLES = ("superadmin", "admin", "user", "guest")  # = auth.core.ROLE_LEVELS


@dataclass(frozen=True)
class Spec:
    """Describes one kind of backed-up database.

    ``prefix``   file-name prefix (``auth`` -> ``auth-YYYYMMDD-HHMMSS-manual.db``)
    ``folder``   directory next to the database that holds the backups
    ``kinds``    allowed kinds (the part after the time stamp)
    ``subdirs``  kind -> sub-folder of ``folder`` (e.g. automatic backups live apart)
    ``validate`` function(path) raising ValueError for an unusable file
    """

    prefix: str
    folder: str
    kinds: tuple
    validate: Callable[[Path], None]
    subdirs: dict = field(default_factory=dict)

    @property
    def name_re(self):
        kinds = "|".join(self.kinds)
        return re.compile(rf"^{re.escape(self.prefix)}-(\d{{8}})-(\d{{6}})(?:-({kinds}))?\.db$")


# ------------------------------------------------------------------ helpers
def format_size(num_bytes: int) -> str:
    """Human readable size: ``812 B``, ``12.4 KB``, ``3.20 MB``."""
    if num_bytes < 1024:
        return f"{num_bytes} B"
    if num_bytes < 1024 * 1024:
        return f"{num_bytes / 1024:.1f} KB"
    return f"{num_bytes / (1024 * 1024):.2f} MB"


def _kind_of(spec: Spec, name: str) -> str:
    match = spec.name_re.fullmatch(name)
    return match.group(3) if match and match.group(3) else "manual"


def folder_for(spec: Spec, db_path: Path, kind: str = "manual") -> Path:
    """Folder that holds backups of this kind (created on demand)."""
    folder = Path(db_path).parent / spec.folder
    if kind in spec.subdirs:
        folder = folder / spec.subdirs[kind]
    folder.mkdir(parents=True, exist_ok=True)
    return folder


def _all_folders(spec: Spec, db_path: Path) -> list[Path]:
    folders = [folder_for(spec, db_path)]
    folders += [folder_for(spec, db_path, kind) for kind in spec.subdirs]
    return folders


def valid_name(spec: Spec, name) -> bool:
    return isinstance(name, str) and bool(spec.name_re.fullmatch(name))


def path_of(spec: Spec, db_path: Path, name: str) -> Path:
    """Absolute path of an existing backup. Raises ValueError for a bad name."""
    if not valid_name(spec, name):
        raise ValueError(t("err_backup_name"))
    path = folder_for(spec, db_path, _kind_of(spec, name)) / name
    if not path.is_file():
        raise ValueError(t("err_backup_missing"))
    return path


def _info(spec: Spec, path: Path) -> dict:
    stat = path.stat()
    kind = _kind_of(spec, path.name)
    return {
        "name": path.name,
        "kind": kind,
        "location": spec.subdirs.get(kind, ""),
        "size": stat.st_size,
        "created": datetime.fromtimestamp(stat.st_mtime, timezone.utc).strftime(
            "%Y-%m-%d %H:%M:%S"
        ),
    }


def _free_name(spec: Spec, folder: Path, kind: str) -> str:
    """A name for 'now' that does not exist yet (bumps the second on a clash)."""
    moment = datetime.now(timezone.utc).replace(microsecond=0)
    while True:
        name = f"{spec.prefix}-{moment:%Y%m%d-%H%M%S}-{kind}.db"
        if not (folder / name).exists():
            return name
        moment += timedelta(seconds=1)


def _check_integrity(path: Path):
    """Open read-only, run the integrity check, return the open connection."""
    con = sqlite3.connect(f"{Path(path).resolve().as_uri()}?mode=ro", uri=True)
    try:
        # Never let schema objects of an untrusted file run code in our queries.
        con.execute("PRAGMA trusted_schema=OFF")
        if con.execute("PRAGMA integrity_check").fetchone()[0] != "ok":
            raise ValueError(t("err_backup_invalid"))
        # Triggers / views would be copied into the live database by a restore and
        # could silently change rows later (e.g. promote an account). Our own
        # databases never contain any, so a file that does is rejected.
        if con.execute(
            "SELECT COUNT(*) FROM sqlite_master WHERE type IN ('trigger','view')"
        ).fetchone()[0]:
            raise ValueError(t("err_backup_invalid"))
    except Exception:
        con.close()
        raise
    return con


def _validate_accounts(path: Path) -> None:
    try:
        with closing(_check_integrity(path)) as con:
            columns = {row[1] for row in con.execute("PRAGMA table_info(users)").fetchall()}
            if not _REQUIRED_COLUMNS <= columns:
                raise ValueError(t("err_backup_invalid"))
            marks = ",".join("?" * len(_VALID_ROLES))
            if con.execute(
                f"SELECT COUNT(*) FROM users WHERE role NOT IN ({marks})", _VALID_ROLES
            ).fetchone()[0]:
                raise ValueError(t("err_backup_invalid"))
            has_superadmin = con.execute(
                "SELECT COUNT(*) FROM users WHERE role='superadmin' AND is_active=1"
            ).fetchone()[0]
            if not has_superadmin:
                raise ValueError(t("err_backup_no_superadmin"))
    except sqlite3.DatabaseError as exc:
        raise ValueError(t("err_backup_invalid")) from exc


def _private(path: Path) -> None:
    """Backups hold password hashes: owner read/write only (best effort)."""
    try:
        os.chmod(path, 0o600)
    except OSError:
        pass


# ------------------------------------------------------- generic operations
def engine_create(spec: Spec, db_path: Path, kind: str = "manual") -> dict:
    """Copy the live database into a new backup file (SQLite online backup)."""
    if kind not in spec.kinds:
        raise ValueError(f"unknown backup kind: {kind}")
    folder = folder_for(spec, db_path, kind)
    target = folder / _free_name(spec, folder, kind)
    partial = target.with_suffix(".partial")
    try:
        with closing(sqlite3.connect(db_path)) as src, closing(sqlite3.connect(partial)) as dst:
            src.backup(dst)
        _private(partial)
        os.replace(partial, target)
    finally:
        partial.unlink(missing_ok=True)
    return _info(spec, target)


def engine_list(spec: Spec, db_path: Path) -> list[dict]:
    """All backups (every folder of the spec), newest first."""
    items = []
    for folder in _all_folders(spec, db_path):
        for path in folder.iterdir():
            if path.is_file() and valid_name(spec, path.name):
                items.append(_info(spec, path))
    return sorted(items, key=lambda item: item["name"], reverse=True)


def engine_delete(spec: Spec, db_path: Path, name: str) -> None:
    path_of(spec, db_path, name).unlink()


def engine_read(spec: Spec, db_path: Path, name: str) -> bytes:
    return path_of(spec, db_path, name).read_bytes()


def engine_import(spec: Spec, db_path: Path, data: bytes) -> dict:
    """Store an uploaded database file as a new ``-uploaded`` backup."""
    if not data or not data.startswith(_SQLITE_MAGIC):
        raise ValueError(t("err_backup_invalid"))
    if len(data) > MAX_IMPORT_BYTES:
        raise ValueError(t("err_backup_too_large", n=MAX_IMPORT_BYTES // (1024 * 1024)))
    folder = folder_for(spec, db_path, "uploaded")
    target = folder / _free_name(spec, folder, "uploaded")
    partial = target.with_suffix(".partial")
    try:
        partial.write_bytes(data)
        _private(partial)
        spec.validate(partial)
        os.replace(partial, target)
    finally:
        partial.unlink(missing_ok=True)
    return _info(spec, target)


# --------------------------------------------------- accounts database flavour
ACCOUNTS = Spec(
    prefix="auth", folder=BACKUP_DIRNAME, kinds=KINDS, validate=_validate_accounts
)


def backup_dir(db_path: Path) -> Path:
    return folder_for(ACCOUNTS, db_path)


def is_valid_name(name) -> bool:
    """True for names this module could have generated."""
    return valid_name(ACCOUNTS, name)


def backup_path(db_path: Path, name: str) -> Path:
    return path_of(ACCOUNTS, db_path, name)


def validate_backup_file(path: Path) -> None:
    """Raise ValueError unless ``path`` is a usable accounts database."""
    _validate_accounts(path)


# --------------------------------------------------------------- operations
def create(db_path: Path, kind: str = "manual") -> dict:
    return engine_create(ACCOUNTS, db_path, kind)


def list_backups(db_path: Path) -> list[dict]:
    return engine_list(ACCOUNTS, db_path)


def delete(db_path: Path, name: str) -> None:
    engine_delete(ACCOUNTS, db_path, name)


def read_bytes(db_path: Path, name: str) -> bytes:
    return engine_read(ACCOUNTS, db_path, name)


def import_bytes(db_path: Path, data: bytes) -> dict:
    return engine_import(ACCOUNTS, db_path, data)


def restore(db_path: Path, name: str, migrate=None) -> dict:
    """Replace the live database with backup ``name``.

    A ``-prerestore`` safety backup of the current database is made first.
    ``migrate(connection)`` (optional) runs on the restored database so a
    backup taken with an older schema gets the newer columns. Returns
    ``{"restored": <info>, "safety": <info>, "users": <row count>}``.
    """
    source = backup_path(db_path, name)
    validate_backup_file(source)
    safety = create(db_path, "prerestore")
    with closing(sqlite3.connect(f"{source.resolve().as_uri()}?mode=ro", uri=True)) as src, \
            closing(sqlite3.connect(db_path)) as dst:
        src.backup(dst)
        if migrate is not None:
            migrate(dst)
            dst.commit()
        users = dst.execute("SELECT COUNT(*) FROM users").fetchone()[0]
    return {"restored": _info(ACCOUNTS, source), "safety": safety, "users": users}
